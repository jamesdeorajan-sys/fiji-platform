// Builds cloudflare/schema/gate15_d1_schema.sql = Gate 1 isolated schema + Gate 1.5 additions, and records its SHA-256 (LF-normalised).
import fs from 'node:fs'; import path from 'node:path'; import crypto from 'node:crypto'; import { fileURLToPath } from 'node:url';
const here = path.dirname(fileURLToPath(import.meta.url)); const root = path.join(here, '..');
const lf = (s) => s.replace(/\r\n/g, '\n');
const base = lf(fs.readFileSync(path.join(root, '..', 'schema', 'gate1_isolated_schema.sql'), 'utf8'));
const add = lf(fs.readFileSync(path.join(root, 'schema', 'gate15_additions.sql'), 'utf8'));
const out = `-- GENERATED by cloudflare/scripts/build_schema.mjs — do not edit. ISOLATED Gate 1.5 D1 ONLY. Not a production migration.\n${base.trimEnd()}\n\n${add.trimEnd()}\n`;
const sha = crypto.createHash('sha256').update(out).digest('hex');
fs.writeFileSync(path.join(root, 'schema', 'gate15_d1_schema.sql'), out);
fs.writeFileSync(path.join(root, 'schema', 'gate15_d1_schema.sha256'), `${sha}  gate15_d1_schema.sql\n`);
console.log(`schema sha256 ${sha}`);
